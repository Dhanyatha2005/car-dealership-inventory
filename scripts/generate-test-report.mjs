// Runs every Vitest suite with the JSON reporter and writes docs/test-report.md.
// Usage: npm run test:report   (Postgres must be up for the integration suite: npm run db:up)
import { execSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const suites = [
  { name: 'Shared contracts (unit)', cmd: 'npx vitest run', cwd: 'packages/shared' },
  { name: 'API (unit)', cmd: 'npx vitest run --project unit', cwd: 'apps/api' },
  {
    name: 'API (integration, PostgreSQL)',
    cmd: 'npx dotenv -e .env.test -- npx vitest run --project integration',
    cwd: 'apps/api',
  },
  { name: 'Web (React Testing Library)', cmd: 'npx vitest run', cwd: 'apps/web' },
];

const dir = mkdtempSync(join(tmpdir(), 'kata-report-'));
const rows = [];
const failures = [];

for (const [i, suite] of suites.entries()) {
  const out = join(dir, `${i}.json`);
  try {
    execSync(`${suite.cmd} --reporter=json --outputFile=${out}`, {
      cwd: suite.cwd,
      stdio: 'ignore',
    });
  } catch {
    // Non-zero exit means failing tests; the JSON file still records them.
  }
  let r;
  try {
    r = JSON.parse(readFileSync(out, 'utf8'));
  } catch {
    rows.push(`| ${suite.name} | – | – | – | did not run |`);
    continue;
  }
  rows.push(
    `| ${suite.name} | ${r.numTotalTestSuites ?? '–'} | ${r.numTotalTests} | ${r.numPassedTests} | ${r.numFailedTests} |`,
  );
  for (const file of r.testResults ?? []) {
    for (const t of file.assertionResults ?? []) {
      if (t.status === 'failed') failures.push(`- ${suite.name}: ${t.fullName}`);
    }
  }
}

const md = `# Test Report

Generated by \`npm run test:report\` on ${new Date().toISOString()}.

| Suite | Groups | Tests | Passed | Failed |
| ----- | ------ | ----- | ------ | ------ |
${rows.join('\n')}

${failures.length ? `## Failing tests\n\n${failures.join('\n')}\n` : 'All tests passed.\n'}`;

writeFileSync('docs/test-report.md', md);
console.log(md);
